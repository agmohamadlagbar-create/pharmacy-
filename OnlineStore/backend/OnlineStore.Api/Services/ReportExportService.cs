    private static string T(string key, string lang)
    {
        if (string.IsNullOrEmpty(lang)) return key;
        var normalizedLang = lang.ToLower().Trim();
        if (normalizedLang.StartsWith("ar")) normalizedLang = "ar";
        else if (normalizedLang.StartsWith("tr")) normalizedLang = "tr";
        else normalizedLang = "en";

        if (Translations.TryGetValue(normalizedLang, out var dict) && dict.TryGetValue(key, out var translated))
        {
            return translated;
        }
        return key;
    }

    // ═══════════════════════════════════════════════════
    //  PDF — Monthly Report
    // ═══════════════════════════════════════════════════

    public byte[] GenerateMonthlyPdf(MonthlyReportDto report, string shopName, string lang)
    {
        var document = Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Size(PageSizes.A4);
                page.Margin(40);
                page.DefaultTextStyle(x => x.FontSize(10));

                page.Header().Element(h => ComposeHeader(h, shopName, $"{T("Monthly Sales Report — ", lang)}{T(report.MonthName, lang)} {report.Year}", lang));

                page.Content().Element(content =>
                {
                    content.PaddingVertical(10).Column(col =>
                    {
                        col.Spacing(15);

                        // Summary section
                        col.Item().Element(e => ComposeSummarySection(e,
                            report.CurrencySymbol, report.TotalRevenue, report.TotalOrders,
                            report.AverageOrderValue, report.RevenueGrowthPercent, report.OrderGrowthPercent, lang));

                        // Top Products Table
                        if (report.TopProducts.Count > 0)
                        {
                            col.Item().Element(e => ComposeTopProductsTable(e, report.TopProducts, report.CurrencySymbol, lang));
                        }

                        // Daily Sales Table
                        if (report.DailySales.Count > 0)
                        {
                            col.Item().Element(e => ComposeDailySalesTable(e, report.DailySales, report.CurrencySymbol, lang));
                        }
                    });
                });

                page.Footer().Element(f => ComposeFooter(f, lang));
            });
        });

        return document.GeneratePdf();
    }

    // ═══════════════════════════════════════════════════
    //  PDF — Yearly Report
    // ═══════════════════════════════════════════════════

    public byte[] GenerateYearlyPdf(YearlyReportDto report, string shopName, string lang)
    {
        var document = Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Size(PageSizes.A4);
                page.Margin(40);
                page.DefaultTextStyle(x => x.FontSize(10));

                page.Header().Element(h => ComposeHeader(h, shopName, $"{T("Yearly Sales Report — ", lang)}{report.Year}", lang));

                page.Content().Element(content =>
                {
                    content.PaddingVertical(10).Column(col =>
                    {
                        col.Spacing(15);

                        // Summary
                        col.Item().Text(text =>
                        {
                            text.Span(T("Total Revenue", lang) + ": ").Bold();
                            text.Span($"{report.CurrencySymbol}{report.TotalRevenue:N2}");
                        });
                        col.Item().Text(text =>
                        {
                            text.Span(T("Total Orders", lang) + ": ").Bold();
                            text.Span($"{report.TotalOrders:N0}");
                        });
                        col.Item().Text(text =>
                        {
                            text.Span(T("Average Order Value", lang) + ": ").Bold();
                            text.Span($"{report.CurrencySymbol}{report.AverageOrderValue:N2}");
                        });

                        // Monthly Breakdown
                        if (report.MonthlyBreakdown.Count > 0)
                        {
                            col.Item().PaddingTop(10).Text(T("Monthly Revenue Breakdown", lang)).Bold().FontSize(12);
                            col.Item().Table(table =>
                            {
                                table.ColumnsDefinition(columns =>
                                {
                                    columns.RelativeColumn(3);
                                    columns.RelativeColumn(2);
                                    columns.RelativeColumn(1.5f);
                                });

                                table.Header(header =>
                                {
                                    header.Cell().Background(Colors.Grey.Lighten3).Padding(5).Text(T("Month", lang)).Bold();
                                    header.Cell().Background(Colors.Grey.Lighten3).Padding(5).AlignRight().Text(T("Revenue", lang)).Bold();
                                    header.Cell().Background(Colors.Grey.Lighten3).Padding(5).AlignRight().Text(T("Orders", lang)).Bold();
                                });

                                foreach (var m in report.MonthlyBreakdown)
                                {
                                    table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten2).Padding(4).Text(T(m.Month, lang));
                                    table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten2).Padding(4).AlignRight().Text($"{report.CurrencySymbol}{m.Revenue:N2}");
                                    table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten2).Padding(4).AlignRight().Text($"{m.OrderCount}");
                                }
                            });
                        }

                        // Growth Trends
                        if (report.GrowthTrends.Count > 0)
                        {
                            col.Item().PaddingTop(10).Text(T("Growth Trends (Month-over-Month)", lang)).Bold().FontSize(12);
                            col.Item().Table(table =>
                            {
                                table.ColumnsDefinition(columns =>
                                {
                                    columns.RelativeColumn(2);
                                    columns.RelativeColumn(2);
                                    columns.RelativeColumn(2);
                                });

                                table.Header(header =>
                                {
                                    header.Cell().Background(Colors.Grey.Lighten3).Padding(5).Text(T("Month", lang)).Bold();
                                    header.Cell().Background(Colors.Grey.Lighten3).Padding(5).AlignRight().Text(T("Revenue Growth", lang)).Bold();
                                    header.Cell().Background(Colors.Grey.Lighten3).Padding(5).AlignRight().Text(T("Order Growth", lang)).Bold();
                                });

                                foreach (var g in report.GrowthTrends)
                                {
                                    table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten2).Padding(4).Text(T(g.Month, lang));
                                    table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten2).Padding(4).AlignRight().Text($"{g.RevenueGrowthPercent:+0.0;-0.0;0.0}%");
                                    table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten2).Padding(4).AlignRight().Text($"{g.OrderGrowthPercent:+0.0;-0.0;0.0}%");
                                }
                            });
                        }

                        // Top Products
                        if (report.TopProducts.Count > 0)
                        {
                            col.Item().Element(e => ComposeTopProductsTable(e, report.TopProducts, report.CurrencySymbol, lang));
                        }
                    });
                });

                page.Footer().Element(f => ComposeFooter(f, lang));
            });
        });

        return document.GeneratePdf();
    }

    // ═══════════════════════════════════════════════════
    //  Excel — Monthly Report
    // ═══════════════════════════════════════════════════

    public byte[] GenerateMonthlyExcel(MonthlyReportDto report, string shopName, string lang)
    {
        using var workbook = new XLWorkbook();

        // Revenue Sheet
        var revenueSheet = workbook.Worksheets.Add(T("Revenue Summary", lang));
        revenueSheet.Cell(1, 1).Value = $"{shopName} — {T("Monthly Report: ", lang)}{T(report.MonthName, lang)} {report.Year}";
        revenueSheet.Cell(1, 1).Style.Font.Bold = true;
        revenueSheet.Cell(1, 1).Style.Font.FontSize = 14;
        revenueSheet.Range(1, 1, 1, 4).Merge();

        revenueSheet.Cell(3, 1).Value = T("Metric", lang);
        revenueSheet.Cell(3, 2).Value = T("Value", lang);
        StyleHeaderRow(revenueSheet, 3, 2);

        revenueSheet.Cell(4, 1).Value = T("Total Revenue", lang);
        revenueSheet.Cell(4, 2).Value = report.TotalRevenue;
        revenueSheet.Cell(4, 2).Style.NumberFormat.Format = $"\"{report.CurrencySymbol}\"#,##0.00";

        revenueSheet.Cell(5, 1).Value = T("Total Orders", lang);
        revenueSheet.Cell(5, 2).Value = report.TotalOrders;

        revenueSheet.Cell(6, 1).Value = T("Average Order Value", lang);
        revenueSheet.Cell(6, 2).Value = report.AverageOrderValue;
        revenueSheet.Cell(6, 2).Style.NumberFormat.Format = $"\"{report.CurrencySymbol}\"#,##0.00";

        revenueSheet.Cell(7, 1).Value = T("Revenue Growth", lang);
        revenueSheet.Cell(7, 2).Value = report.RevenueGrowthPercent / 100;
        revenueSheet.Cell(7, 2).Style.NumberFormat.Format = "0.0%";

        revenueSheet.Cell(8, 1).Value = T("Order Growth", lang);
        revenueSheet.Cell(8, 2).Value = report.OrderGrowthPercent / 100;
        revenueSheet.Cell(8, 2).Style.NumberFormat.Format = "0.0%";

        revenueSheet.Columns().AdjustToContents();

        // Daily Sales Sheet
        var dailySheet = workbook.Worksheets.Add(T("Daily Sales", lang));
        dailySheet.Cell(1, 1).Value = T("Date", lang);
        dailySheet.Cell(1, 2).Value = T("Revenue", lang);
        dailySheet.Cell(1, 3).Value = T("Orders", lang);
        StyleHeaderRow(dailySheet, 1, 3);

        for (int i = 0; i < report.DailySales.Count; i++)
        {
            var ds = report.DailySales[i];
            dailySheet.Cell(i + 2, 1).Value = ds.Date;
            dailySheet.Cell(i + 2, 2).Value = ds.Revenue;
            dailySheet.Cell(i + 2, 2).Style.NumberFormat.Format = $"\"{report.CurrencySymbol}\"#,##0.00";
            dailySheet.Cell(i + 2, 3).Value = ds.OrderCount;
        }
        dailySheet.Columns().AdjustToContents();

        // Top Products Sheet
        var productsSheet = workbook.Worksheets.Add(T("Top Products", lang));
        productsSheet.Cell(1, 1).Value = T("Rank", lang);
        productsSheet.Cell(1, 2).Value = T("Product Name", lang);
        productsSheet.Cell(1, 3).Value = T("Quantity Sold", lang);
        productsSheet.Cell(1, 4).Value = T("Revenue", lang);
        StyleHeaderRow(productsSheet, 1, 4);

        for (int i = 0; i < report.TopProducts.Count; i++)
        {
            var tp = report.TopProducts[i];
            productsSheet.Cell(i + 2, 1).Value = i + 1;
            productsSheet.Cell(i + 2, 2).Value = tp.ProductName;
            productsSheet.Cell(i + 2, 3).Value = tp.QuantitySold;
            productsSheet.Cell(i + 2, 4).Value = tp.Revenue;
            productsSheet.Cell(i + 2, 4).Style.NumberFormat.Format = $"\"{report.CurrencySymbol}\"#,##0.00";
        }
        productsSheet.Columns().AdjustToContents();

        using var stream = new MemoryStream();
        workbook.SaveAs(stream);
        return stream.ToArray();
    }

