                table.Header(header =>
                {
                    header.Cell().Background(Colors.Grey.Lighten3).Padding(5).Text(T("Date", lang)).Bold();
                    header.Cell().Background(Colors.Grey.Lighten3).Padding(5).AlignRight().Text(T("Revenue", lang)).Bold();
                    header.Cell().Background(Colors.Grey.Lighten3).Padding(5).AlignRight().Text(T("Orders", lang)).Bold();
                });

                foreach (var s in sales)
                {
                    table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten2).Padding(4).Text(s.Date);
                    table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten2).Padding(4).AlignRight().Text($"{currency}{s.Revenue:N2}");
                    table.Cell().BorderBottom(1).BorderColor(Colors.Grey.Lighten2).Padding(4).AlignRight().Text($"{s.OrderCount}");
                }
            });
        });
    }

    private static void ComposeFooter(IContainer container, string lang)
    {
        container.AlignCenter().Text(text =>
        {
            text.DefaultTextStyle(x => x.FontSize(8).FontColor(Colors.Grey.Medium));
            text.Span(T("Page ", lang));
            text.CurrentPageNumber();
            text.Span(T(" of ", lang));
            text.TotalPages();
            text.Span(T(" — Generated by LAGBAR Store Analytics", lang));
        });
    }

